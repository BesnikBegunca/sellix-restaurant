/// Spacing scale (pixels). Use these constants for consistent layout rhythm.
abstract final class AppSpacing {
  static const double xs   = 4;
  static const double sm   = 8;
  static const double md   = 12;
  static const double base = 16;
  static const double lg   = 24;
  static const double xl   = 32;
  static const double xxl  = 48;

  /// Standard page padding (all sides).
  static const double pagePadding = 32;

  /// Standard card internal padding.
  static const double cardPadding = 24;

  /// Gap between sibling cards on a page.
  static const double cardGap = 24;

  /// Sidebar width when expanded.
  static const double sidebarWidth = 256;

  /// Sidebar width when collapsed.
  static const double sidebarCollapsed = 80;

  /// Top header height.
  static const double headerHeight = 80;
}
